    private static String pem(String type, byte[] content) throws IOException {
        StringWriter out = new StringWriter();
        try (PemWriter writer = new PemWriter(out)) {
            writer.writeObject(new PemObject(type, content));
        }
        return out.toString();
    }

    @Test
    void thePemWalletKeyIsReencryptedAndTheCertificateKept() throws Exception {
        byte[] encryptedKey = new JcaPKCS8EncryptedPrivateKeyInfoBuilder(keyPair.getPrivate())
                .build(encryptor(CONTAINER_PASSWORD)).getEncoded();
        String certificatePem = pem("CERTIFICATE", certificate.getEncoded());
        String original = "Bag Attributes\n    friendlyName: orakey\n" + pem("ENCRYPTED PRIVATE KEY", encryptedKey)
                + certificatePem;

        String reencrypted = new String(WalletKeystores.reencryptPem(original.getBytes(StandardCharsets.US_ASCII),
                CONTAINER_PASSWORD, REQUEST_PASSWORD), StandardCharsets.US_ASCII);

        assertTrue(reencrypted.startsWith("Bag Attributes\n    friendlyName: orakey\n"));
        assertTrue(reencrypted.endsWith(certificatePem));
        String block = reencrypted.substring(reencrypted.indexOf("-----BEGIN ENCRYPTED PRIVATE KEY-----"),
                reencrypted.indexOf(certificatePem));
        assertNotEquals(pem("ENCRYPTED PRIVATE KEY", encryptedKey), block);
        String body = block.replaceAll("-----(BEGIN|END) ENCRYPTED PRIVATE KEY-----", "").replaceAll("\\s", "");
        byte[] decrypted = new PKCS8EncryptedPrivateKeyInfo(Base64.getDecoder().decode(body))
                .decryptPrivateKeyInfo(new JcePKCSPBEInputDecryptorProviderBuilder()
                        .setProvider(BC).build(REQUEST_PASSWORD)).getEncoded();
        assertArrayEquals(keyPair.getPrivate().getEncoded(), decrypted);
    }

    @Test
    void theJavaKeystoresOpenWithTheNewPassword() throws Exception {
        KeyStore keystore = KeyStore.getInstance("JKS");
        keystore.load(null, null);
        keystore.setKeyEntry("orakey", keyPair.getPrivate(), CONTAINER_PASSWORD, new Certificate[]{certificate});
        keystore.setCertificateEntry("trusted", certificate);
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        keystore.store(bytes, CONTAINER_PASSWORD);

        byte[] reencrypted = WalletKeystores.reencryptJks(bytes.toByteArray(), CONTAINER_PASSWORD, REQUEST_PASSWORD);

        KeyStore reopened = KeyStore.getInstance("JKS");
        reopened.load(new ByteArrayInputStream(reencrypted), REQUEST_PASSWORD);
        PrivateKey key = (PrivateKey) reopened.getKey("orakey", REQUEST_PASSWORD);
        assertArrayEquals(keyPair.getPrivate().getEncoded(), key.getEncoded());
        assertEquals(certificate, reopened.getCertificate("trusted"));
        assertThrows(IOException.class, () -> KeyStore.getInstance("JKS")
                .load(new ByteArrayInputStream(reencrypted), CONTAINER_PASSWORD));
    }

    // ── The wallet zip ─────────────────────────────────────────────────────────

    private static Map<String, byte[]> unzip(byte[] zip) throws IOException {
        Map<String, byte[]> files = new LinkedHashMap<>();
        try (ZipInputStream in = new ZipInputStream(new ByteArrayInputStream(zip))) {
            for (ZipEntry entry = in.getNextEntry(); entry != null; entry = in.getNextEntry()) {
                files.put(entry.getName(), in.readAllBytes());
            }
        }
        return files;
    }

    @Test
    void theRealWalletRewritesTnsnamesReencryptsTheKeystoresAndPassesTheRestThrough() throws Exception {
        byte[] sso = {(byte) 0xA1, (byte) 0xF8, 0x4E, 0x36, 0x00, 0x01};
        Map<String, byte[]> container = new LinkedHashMap<>();
        container.put("cwallet.sso", sso);
        container.put("ewallet.p12", containerPkcs12(new byte[]{42}));
        container.put("tnsnames.ora", TNSNAMES.getBytes(StandardCharsets.UTF_8));
        container.put("sqlnet.ora", "WALLET_LOCATION = (SOURCE = (METHOD = file))\n".getBytes(StandardCharsets.UTF_8));
        container.put("README", "readme".getBytes(StandardCharsets.UTF_8));
        Map<String, byte[]> containerOnly = Map.of("cwallet.sso.lck", new byte[0], "ewallet.p12.lck", new byte[0],
                ".runstate", "running".getBytes(StandardCharsets.UTF_8));
        Map<String, byte[]> withLocks = new LinkedHashMap<>(container);
        withLocks.putAll(containerOnly);

        Map<String, byte[]> wallet = unzip(AutonomousDatabaseWallet.zip(withLocks, CONTAINER_PASSWORD,
                REQUEST_PASSWORD, "localhost", 11530));

        assertEquals(List.copyOf(container.keySet()), List.copyOf(wallet.keySet()),
                "the container's lock and state files stay out of the wallet");
        assertArrayEquals(sso, wallet.get("cwallet.sso"), "the auto-login wallet needs no password");
        assertArrayEquals(container.get("sqlnet.ora"), wallet.get("sqlnet.ora"));
        assertArrayEquals(container.get("README"), wallet.get("README"));
        String tnsnames = new String(wallet.get("tnsnames.ora"), StandardCharsets.UTF_8);
        assertTrue(tnsnames.startsWith("myatp_high = (description="), tnsnames);
        assertFalse(tnsnames.contains("_tls"));
        assertFalse(tnsnames.contains("port=1522"));
        KeyStore p12 = KeyStore.getInstance("PKCS12", "SUN");
        p12.load(new ByteArrayInputStream(wallet.get("ewallet.p12")), REQUEST_PASSWORD);
        assertNotNull(p12.getKey("orakey", REQUEST_PASSWORD));
    }
