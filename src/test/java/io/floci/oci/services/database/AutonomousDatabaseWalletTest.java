    @BeforeAll
    static void createKey() throws Exception {
        if (Security.getProvider(BouncyCastleProvider.PROVIDER_NAME) == null) {
            Security.addProvider(new BouncyCastleProvider());
        }
        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        keyPair = generator.generateKeyPair();
        Instant now = Instant.now();
        X500Name subject = new X500Name("CN=localhost");
        certificate = new JcaX509CertificateConverter().getCertificate(new JcaX509v3CertificateBuilder(subject,
                BigInteger.ONE, Date.from(now), Date.from(now.plus(Duration.ofDays(1))), subject, keyPair.getPublic())
                .build(new JcaContentSignerBuilder("SHA256withRSA").build(keyPair.getPrivate())));
    }

