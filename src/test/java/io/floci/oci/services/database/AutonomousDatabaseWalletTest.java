    // ── Keystores ──────────────────────────────────────────────────────────────

    private static OutputEncryptor encryptor(char[] password) throws Exception {
        return new JcePKCSPBEOutputEncryptorBuilder(NISTObjectIdentifiers.id_aes256_CBC)
                .setProvider(BC).build(password);
    }

    /** A PKCS12 file shaped like ewallet.p12: a key bag, a certificate bag and an Oracle secret bag. */
    private static byte[] containerPkcs12(byte[] secret) throws Exception {
        PKCS12SafeBag key = new JcaPKCS12SafeBagBuilder(keyPair.getPrivate(), encryptor(CONTAINER_PASSWORD))
                .addBagAttribute(PKCSObjectIdentifiers.pkcs_9_at_friendlyName, new DERBMPString("orakey"))
                .addBagAttribute(PKCSObjectIdentifiers.pkcs_9_at_localKeyId, new DEROctetString(new byte[]{1, 2}))
                .build();
        PKCS12SafeBag cert = new JcaPKCS12SafeBagBuilder(certificate)
                .addBagAttribute(PKCSObjectIdentifiers.pkcs_9_at_localKeyId, new DEROctetString(new byte[]{1, 2}))
                .build();
        PKCS12SafeBag oracleSecret = new PKCS12SafeBag(new SafeBag(ORACLE_SECRET_BAG,
                new DERSequence(new DERUTF8String(new String(secret, StandardCharsets.UTF_8)))));
        PKCS12PfxPduBuilder builder = new PKCS12PfxPduBuilder();
        builder.addData(key);
        builder.addEncryptedData(encryptor(CONTAINER_PASSWORD), new PKCS12SafeBag[]{cert, oracleSecret});
        BcPKCS12MacCalculatorBuilder mac = new BcPKCS12MacCalculatorBuilder(new SHA256Digest(),
                new AlgorithmIdentifier(NISTObjectIdentifiers.id_sha256, DERNull.INSTANCE));
        return builder.build(mac, CONTAINER_PASSWORD).getEncoded();
    }

    private static List<PKCS12SafeBag> bags(byte[] pkcs12, char[] password) throws Exception {
        PKCS12PfxPdu pfx = new PKCS12PfxPdu(pkcs12);
        List<PKCS12SafeBag> bags = new ArrayList<>();
        for (ContentInfo content : pfx.getContentInfos()) {
            PKCS12SafeBagFactory factory = PKCSObjectIdentifiers.encryptedData.equals(content.getContentType())
                    ? new PKCS12SafeBagFactory(content, new JcePKCSPBEInputDecryptorProviderBuilder()
                            .setProvider(BC).build(password))
                    : new PKCS12SafeBagFactory(content);
            bags.addAll(List.of(factory.getSafeBags()));
        }
        return bags;
    }

    @Test
    void thePkcs12WalletOpensWithTheNewPasswordAndKeepsTheOracleSecretBag() throws Exception {
        byte[] secret = "oracle.security.client.connect_string1".getBytes(StandardCharsets.UTF_8);
        byte[] original = containerPkcs12(secret);
        SafeBag originalSecret = bags(original, CONTAINER_PASSWORD).stream()
                .filter(bag -> ORACLE_SECRET_BAG.equals(bag.getType())).findFirst().orElseThrow()
                .toASN1Structure();

        byte[] reencrypted = WalletKeystores.reencryptPkcs12(original, CONTAINER_PASSWORD, REQUEST_PASSWORD);

        List<PKCS12SafeBag> bags = bags(reencrypted, REQUEST_PASSWORD);
        assertEquals(3, bags.size());
        SafeBag secretBag = bags.stream().filter(bag -> ORACLE_SECRET_BAG.equals(bag.getType())).findFirst()
                .orElseThrow().toASN1Structure();
        assertArrayEquals(originalSecret.getEncoded(), secretBag.getEncoded(), "the secret bag is copied as it was");
        assertTrue(new PKCS12PfxPdu(reencrypted).isMacValid(
                new BcPKCS12MacCalculatorBuilderProvider(BcDefaultDigestProvider.INSTANCE), REQUEST_PASSWORD));

        PKCS12SafeBag key = bags.stream().filter(bag -> PKCSObjectIdentifiers.pkcs8ShroudedKeyBag.equals(bag.getType()))
                .findFirst().orElseThrow();
        Attribute[] attributes = key.getAttributes();
        assertEquals(Set.of(PKCSObjectIdentifiers.pkcs_9_at_friendlyName, PKCSObjectIdentifiers.pkcs_9_at_localKeyId),
                Set.of(attributes[0].getAttrType(), attributes[1].getAttrType()), "friendlyName and localKeyId survive");
        byte[] decrypted = ((PKCS8EncryptedPrivateKeyInfo) key.getBagValue()).decryptPrivateKeyInfo(
                new JcePKCSPBEInputDecryptorProviderBuilder().setProvider(BC)
                        .build(REQUEST_PASSWORD)).getEncoded();
        assertArrayEquals(keyPair.getPrivate().getEncoded(), decrypted);
    }

    @Test
    void theJdkOpensTheReencryptedPkcs12WithTheNewPasswordOnly() throws Exception {
        byte[] reencrypted = WalletKeystores.reencryptPkcs12(containerPkcs12(new byte[]{42}), CONTAINER_PASSWORD,
                REQUEST_PASSWORD);

        KeyStore store = KeyStore.getInstance("PKCS12", "SUN");
        store.load(new ByteArrayInputStream(reencrypted), REQUEST_PASSWORD);
        Key key = store.getKey("orakey", REQUEST_PASSWORD);
        assertArrayEquals(keyPair.getPrivate().getEncoded(), key.getEncoded());
        assertThrows(IOException.class, () -> KeyStore.getInstance("PKCS12", "SUN")
                .load(new ByteArrayInputStream(reencrypted), CONTAINER_PASSWORD));
    }

