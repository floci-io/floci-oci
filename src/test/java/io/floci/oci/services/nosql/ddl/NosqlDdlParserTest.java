package io.floci.oci.services.nosql.ddl;

import io.floci.oci.services.nosql.ddl.NosqlDdlParser.AlterTable;
import io.floci.oci.services.nosql.ddl.NosqlDdlParser.ColumnDef;
import io.floci.oci.services.nosql.ddl.NosqlDdlParser.CreateIndex;
import io.floci.oci.services.nosql.ddl.NosqlDdlParser.CreateTable;
import io.floci.oci.services.nosql.ddl.NosqlDdlParser.DropIndex;
import io.floci.oci.services.nosql.ddl.NosqlDdlParser.DropTable;
import io.floci.oci.services.nosql.query.NosqlSyntaxException;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class NosqlDdlParserTest {

    /** The DDL of terraform-provider-oci's nosql_table acceptance test. */
    static final String TERRAFORM_DDL = "CREATE TABLE IF NOT EXISTS test_table(id INTEGER GENERATED ALWAYS AS"
            + " IDENTITY, name STRING, age STRING, info JSON, guid STRING AS UUID, PRIMARY KEY(SHARD(id)))";

    @Test
    void terraformAcceptanceDdl() {
        CreateTable table = (CreateTable) NosqlDdlParser.parse(TERRAFORM_DDL);

        assertEquals("test_table", table.tableName());
        assertTrue(table.ifNotExists());
        assertEquals(List.of("id", "name", "age", "info", "guid"),
                table.columns().stream().map(ColumnDef::name).toList());
        ColumnDef id = table.columns().getFirst();
        assertEquals("INTEGER", id.type());
        assertFalse(id.nullable());
        assertTrue(id.identity().always());
        assertFalse(id.identity().onNull());
        ColumnDef guid = table.columns().get(4);
        assertTrue(guid.asUuid());
        assertFalse(guid.uuidGenerated());
        assertTrue(table.columns().get(1).nullable());
        assertEquals(List.of("id"), table.primaryKey());
        assertEquals(List.of("id"), table.shardKey());
        assertNull(table.ttl());
    }

    @Test
    void compositePrimaryKeyWithShardKey() {
        CreateTable table = (CreateTable) NosqlDdlParser.parse("create table orders (customer LONG,"
                + " orderId STRING, placed TIMESTAMP(3), total NUMBER DEFAULT 0 NOT NULL,"
                + " PRIMARY KEY (SHARD(customer), orderId))");

        assertEquals(List.of("customer", "orderId"), table.primaryKey());
        assertEquals(List.of("customer"), table.shardKey());
        assertEquals("TIMESTAMP(3)", table.columns().get(2).type());
        ColumnDef total = table.columns().get(3);
        assertFalse(total.nullable());
        assertEquals("0", total.defaultValue());
    }

    @Test
    void primaryKeyWithoutShardMakesTheWholeKeyTheShardKey() {
        CreateTable table = (CreateTable) NosqlDdlParser.parse(
                "CREATE TABLE t (a INTEGER, b STRING, PRIMARY KEY (a, b))");

        assertEquals(List.of("a", "b"), table.shardKey());
    }

    @Test
    void ttlInDaysAndHours() {
        CreateTable days = (CreateTable) NosqlDdlParser.parse(
                "CREATE TABLE t (id INTEGER, PRIMARY KEY (id)) USING TTL 7 DAYS");
        assertEquals(7, days.ttl().value());
        assertEquals("DAYS", days.ttl().unit());
        assertEquals(7, days.ttl().days());

        CreateTable hours = (CreateTable) NosqlDdlParser.parse(
                "CREATE TABLE t (id INTEGER, PRIMARY KEY (id)) USING TTL 36 HOURS");
        assertEquals(2, hours.ttl().days());
        assertEquals(36L * 3_600_000L, hours.ttl().millis());
    }

    @Test
    void identityAndUuidOptions() {
        CreateTable table = (CreateTable) NosqlDdlParser.parse("CREATE TABLE t (id LONG GENERATED BY DEFAULT"
                + " ON NULL AS IDENTITY (START WITH 100 INCREMENT BY 5 CACHE 10), u STRING AS UUID GENERATED BY"
                + " DEFAULT, tags ARRAY(STRING), attrs MAP(INTEGER), addr RECORD(city STRING, zip INTEGER),"
                + " color ENUM(red, green), PRIMARY KEY (id))");

        ColumnDef id = table.columns().getFirst();
        assertFalse(id.identity().always());
        assertTrue(id.identity().onNull());
        assertEquals(100, id.identity().start());
        assertEquals(5, id.identity().increment());
        assertTrue(table.columns().get(1).uuidGenerated());
        assertEquals("ARRAY(STRING)", table.columns().get(2).type());
        assertEquals("MAP(INTEGER)", table.columns().get(3).type());
        assertEquals("RECORD(city STRING, zip INTEGER)", table.columns().get(4).type());
        assertEquals("ENUM(red, green)", table.columns().get(5).type());
    }

    @Test
    void alterTableAddDropAndTtl() {
        AlterTable alter = (AlterTable) NosqlDdlParser.parse("ALTER TABLE users (ADD email STRING, DROP age)");
        assertEquals("users", alter.tableName());
        assertEquals("email", alter.added().getFirst().name());
        assertEquals(List.of("age"), alter.dropped());

        AlterTable ttl = (AlterTable) NosqlDdlParser.parse("ALTER TABLE audience_info USING TTL 7 days");
        assertEquals(7, ttl.ttl().value());
    }

    @Test
    void indexOnJsonPath() {
        CreateIndex index = (CreateIndex) NosqlDdlParser.parse(
                "CREATE INDEX IF NOT EXISTS segmentIdx ON audience_info (audience_segment.sports_lover AS STRING,"
                        + " ipaddr)");

        assertEquals("segmentIdx", index.indexName());
        assertEquals("audience_info", index.tableName());
        assertTrue(index.ifNotExists());
        assertEquals("audience_segment", index.keys().getFirst().columnName());
        assertEquals("sports_lover", index.keys().getFirst().jsonPath());
        assertEquals("STRING", index.keys().getFirst().jsonFieldType());
        assertNull(index.keys().get(1).jsonPath());
    }

    @Test
    void dropTableAndIndex() {
        DropTable table = (DropTable) NosqlDdlParser.parse("DROP TABLE IF EXISTS audience_info");
        assertTrue(table.ifExists());
        DropIndex index = (DropIndex) NosqlDdlParser.parse("DROP INDEX idx ON audience_info");
        assertFalse(index.ifExists());
        assertEquals("idx", index.indexName());
    }

    @Test
    void syntaxErrors() {
        assertThrows(NosqlSyntaxException.class,
                () -> NosqlDdlParser.parse("CREATE TABLE t (id INTEGER, PRIMARY KEY (id));"));
        assertThrows(NosqlSyntaxException.class, () -> NosqlDdlParser.parse("CREATE TABLE t (id INTEGER)"));
        assertThrows(NosqlSyntaxException.class,
                () -> NosqlDdlParser.parse("CREATE TABLE t (id INTEGR, PRIMARY KEY (id))"));
        assertThrows(NosqlSyntaxException.class,
                () -> NosqlDdlParser.parse("CREATE TABLE t (id INTEGER, PRIMARY KEY (nope))"));
        assertThrows(NosqlSyntaxException.class,
                () -> NosqlDdlParser.parse("CREATE TABLE t (id INTEGER, doc JSON, PRIMARY KEY (doc))"));
        assertThrows(NosqlSyntaxException.class,
                () -> NosqlDdlParser.parse("CREATE TABLE t (id INTEGER, v STRING NOT NULL, PRIMARY KEY (id))"));
        NosqlSyntaxException error = assertThrows(NosqlSyntaxException.class,
                () -> NosqlDdlParser.parse("SELECT * FROM t"));
        assertTrue(error.getMessage().contains("position 0"), error.getMessage());
    }
}
